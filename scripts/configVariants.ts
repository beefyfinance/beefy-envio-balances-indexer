/** Removes every `@storage(...)` directive, parentheses balanced, plus the whitespace before it. */
export const toLocalSchema = (schema: string): string => {
    let out = '';
    let index = 0;
    while (index < schema.length) {
        const start = schema.indexOf('@storage(', index);
        if (start < 0) {
            out += schema.slice(index);
            break;
        }
        // drop the whitespace (and line break) that separates the directive from what precedes it
        out += schema.slice(index, start).replace(/\s+$/, '');
        let depth = 0;
        let cursor = start + '@storage'.length;
        for (; cursor < schema.length; cursor++) {
            const char = schema[cursor];
            if (char === '(') depth++;
            if (char === ')') {
                depth--;
                if (depth === 0) break;
            }
        }
        if (depth !== 0) {
            throw new Error(`Unbalanced @storage directive at offset ${start}`);
        }
        index = cursor + 1;
    }
    return `${GENERATED_HEADER}\n${out}`;
};

const withHeader = (configYaml: string) => {
    // the yaml-language-server modeline must stay on the first line
    const [first = '', ...rest] = configYaml.split('\n');
    return first.startsWith('# yaml-language-server')
        ? [first, GENERATED_HEADER, ...rest].join('\n')
        : `${GENERATED_HEADER}\n${configYaml}`;
};

/**
 * Every chain syncs over RPC: each `rpc` entry of a chain gets `for: sync` (an existing `for:` is replaced).
 * Without a HyperSync source, ENVIO_API_TOKEN is not needed (it is only read by the HyperSync source).
 */
const toRpcOnly = (configYaml: string): string => {
    const lines = configYaml.split('\n');
    const out: string[] = [];
    let inChains = false;
    for (const line of lines) {
        if (/^chains:\s*$/.test(line)) inChains = true;
        if (inChains && /^ {8}for: /.test(line)) continue;
        out.push(line);
        if (inChains && /^ {6}- url: /.test(line)) out.push('        for: sync');
    }
    const result = out.join('\n');
    const chains = (result.match(/^ {2}- id: /gm) ?? []).length;
    const synced = (result.match(/^ {8}for: sync$/gm) ?? []).length;
    if (chains === 0 || synced < chains) {
        throw new Error(
            `RPC-only config: ${synced} rpc sync entries for ${chains} chains (every chain needs an rpc url)`
        );
    }
    return result;
};

const PROD_STORAGE = /^storage:\n(?: {2}.*\n|\s*#.*\n)+/m;

const postgresOnly = (configYaml: string): string => {
    if (!PROD_STORAGE.test(configYaml)) {
        throw new Error('config.yaml has no top-level `storage:` block');
    }
    const localStorage = [
        `schema: ${LOCAL_SCHEMA_FILE}`,
        'storage:',
        '  postgres:',
        '    default: true',
        '    column_name_format: snake_case',
        '',
        '',
    ].join('\n');
    return configYaml.replace(PROD_STORAGE, localStorage);
};

/** Production storage, RPC sync. */
export const toRpcConfig = (configYaml: string): string => withHeader(toRpcOnly(configYaml));

/** RPC sync, Postgres only, local schema. */
export const toLocalConfig = (configYaml: string): string => withHeader(postgresOnly(toRpcOnly(configYaml)));

/** The variants of a config.yaml content (config.yaml itself is not rewritten). */
export const variantsOf = (configYaml: string, schema: string): Record<string, string> => ({
    [RPC_CONFIG_FILE]: toRpcConfig(configYaml),
    [LOCAL_CONFIG_FILE]: toLocalConfig(configYaml),
    [LOCAL_SCHEMA_FILE]: toLocalSchema(schema),
});

/** Every variant of the current config.yaml and schema.graphql. */
export const generateAll = (root: string): Record<string, string> =>
    variantsOf(readFileSync(join(root, PROD_CONFIG_FILE), 'utf8'), readFileSync(join(root, 'schema.graphql'), 'utf8'));

/** Writes files relative to the project root. */
export const writeFiles = (root: string, files: Record<string, string>) =>
    R.pipe(
        files,
        R.entries(),
        R.forEach(([file, content]) => {
            writeFileSync(join(root, file), content);
        })
    );

const main = () => {
    const root = join(dirname(fileURLToPath(import.meta.url)), '..');
    const files = generateAll(root);
    writeFiles(root, files);
    console.log(`wrote ${R.keys(files).join(', ')}`);
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    main();
}
